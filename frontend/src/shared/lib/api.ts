import type { NFLPlayer } from "@/shared/types/workbench";

export const API_BASE = import.meta.env.VITE_API_BASE ?? "http://localhost:8000";

export interface PbpShardInfo {
  year: number;
  path: string;
}

export interface PlayerDetailPayload {
  player: NFLPlayer;
  shards: PbpShardInfo[];
}

export async function searchPlayers(q: string): Promise<NFLPlayer[]> {
  const params = new URLSearchParams({ q });
  const res = await fetch(`${API_BASE}/search?${params.toString()}`);
  if (!res.ok) {
    throw new Error(`Search failed: ${res.status}`);
  }
  return res.json() as Promise<NFLPlayer[]>;
}

export async function fetchPbpShards(): Promise<PbpShardInfo[]> {
  const res = await fetch(`${API_BASE}/pbp/shards`);
  if (!res.ok) {
    throw new Error(`PBP shards failed: ${res.status}`);
  }
  return res.json() as Promise<PbpShardInfo[]>;
}

export async function fetchCfbPbpShards(): Promise<PbpShardInfo[]> {
  const res = await fetch(`${API_BASE}/cfb/pbp/shards`);
  if (!res.ok) {
    throw new Error(`CFB PBP shards failed: ${res.status}`);
  }
  return res.json() as Promise<PbpShardInfo[]>;
}

export async function fetchPlayerDetail(gsisId: string): Promise<PlayerDetailPayload> {
  const res = await fetch(`${API_BASE}/player/${encodeURIComponent(gsisId)}`);
  if (res.status === 404) {
    throw new Error("Player not found");
  }
  if (!res.ok) {
    throw new Error(`Player fetch failed: ${res.status}`);
  }
  return res.json() as Promise<PlayerDetailPayload>;
}

export function shardParquetUrl(path: string): string {
  if (path.startsWith("http://") || path.startsWith("https://")) {
    return path;
  }
  const base = API_BASE.replace(/\/$/, "");
  const p = path.startsWith("/") ? path : `/${path}`;
  return `${base}${p}`;
}

/** Full URL for `player_index.parquet` on the API (DuckDB-WASM HTTP / range reads). */
export function playerIndexParquetUrl(): string {
  return shardParquetUrl("/data/player_index.parquet");
}

/** Rosetta gold layer: NFL+CFB season aggregates with baked `nfl_id` / `cfb_id` (DuckDB-WASM). */
export function goldUnifiedParquetUrl(): string {
  return shardParquetUrl("/data/gold_unified_performance.parquet");
}

/** DynastyProcess-aligned hub for joins / reference (Telescope track mounts this with gold). */
export function playerHubParquetUrl(): string {
  return shardParquetUrl("/data/player_hub.parquet");
}

/** NLQ entity resolution (generated by Rosetta pipeline). */
export function hubDictionaryJsonUrl(): string {
  return shardParquetUrl("/data/hub_dictionary.json");
}

/** Microscope NLQ: GSIS id dictionary from loaded player_index (API builds JSON). */
export function microscopePlayerDictionaryUrl(): string {
  const base = API_BASE.replace(/\/$/, "");
  return `${base}/nlq/microscope/player-dictionary`;
}
